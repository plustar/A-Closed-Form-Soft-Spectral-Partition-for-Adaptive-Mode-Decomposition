def suite():
    """The four signals of ``synthetic_suite.py``, as (label, signal, fs, transform)."""
    from soft_partition_paper.synthetic_suite import SUITE
    out = []
    for fn, _title, label in SUITE:
        sig, fs, tr = fn()
        out.append((label, sig, fs, tr))
    return out


def run_damd(x, fs, transform):
    """Transform with its defaults at hop 1 (n_fft = 256 for the STFT family) and
    mean-shift detection with its defaults (unit bandwidth, no adaptation)."""
    from softdamd import MeanShift, SoftDAMD, make_transform
    tf = make_transform(transform, hop=1) if transform in ("stft", "ssq_stft") \
        else make_transform(transform)
    return SoftDAMD(tf, MeanShift()).run(x, fs)


def main(alpha: float = ALPHA):
    print_env()
    print(f"\nalpha = {alpha:g}; boundary neighbourhood swept over "
          f"radii {RADII} bins")
    print("'boundary energy'   = fraction of frame energy within r bins of a boundary")
    print("'alloc. difference' = input-power-weighted difference between the hard and")
    print("                      the soft allocation over those bins")
    print("The second column ('Allocation difference' in Table IV) measures how the two")
    print("rules differ; the first is exposure only, and is identical for both masks.")

    with Section("1. The metric, with the detector's own defaults"):
        label, x, fs, tr = suite()[1]              # crossing chirps
        r = run_damd(x, fs, tr)
        report(f"{label} (default detection settings)", r, fs, len(x) / fs, alpha)

    with Section("2. The four signals, with the Experiment D settings"):
        import soft_partition_paper.exp_d_synthetic as ed
        for label, sig, fs_i, tr_i in suite():
            res = ed.run_detection(sig, fs_i, tr_i)
            report(label, res, fs_i, len(sig) / fs_i, alpha)
            appendix_h(res, fs_i, alpha)

    with Section("3. Reading the table"):
        print("    Each block lists the transform, fs, duration, frame count, the bin")
        print("    width in hertz, K_t (mean number of modes per frame) and the")
        print("    neighbourhood width in hertz.  A bin is a different physical width in")
        print("    each row (the SSQ-CWT axis is logarithmic), so the percentages are")
        print("    read together with the neighbourhood width.")
        print("    Table IV of the paper is the same measurement on four third-party")
        print("    recordings that are not included; the signals used here are generated")
        print("    by synthetic_suite.py, so the numbers differ from the paper's.")
        print("    The boundary rows are identical for hard and soft extraction; the")
        print("    allocation-difference rows weight the change in allocation by the")
        print("    input power, and are not energy transferred between modes.")
        print("    Neither quantity is a measure of decomposition quality.")

    print("\nCONCLUSION")
    print("  Boundary energy describes exposure to the Voronoi boundaries; the")
    print("  allocation difference states how much of the input power the soft mask")
    print("  allocates differently from the hard mask, which is what Table IV conveys.")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--alpha", type=float, default=ALPHA)
    args = ap.parse_args()
    main(alpha=args.alpha)
