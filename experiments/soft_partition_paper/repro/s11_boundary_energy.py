"""Boundary exposure and allocation difference (the measurement of Table IV).

Computes the two quantities of Table IV on the four synthetic signals of
``synthetic_suite.py``, together with the detail given in supplementary Appendix H.

DEFINITIONS
-----------
For each frame t with detected centres {w_k,t} and Voronoi boundaries {b_j,t} (the
midpoints between adjacent centres), and a neighbourhood of +-r bins around each
boundary:

    Boundary(r)    = energy P(w,t) in the bins within r bins of any boundary,
                     divided by the total energy of the frame;

    AllocDiff(r)   = sum over the same bins of (1/2) sum_k |s_k^soft - s_k^hard| P(w,t),
                     divided by the total energy of the frame,

both averaged over frames weighted by frame energy.  Boundary measures exposure only:
hard and soft extraction act on the same coefficients in those bins.  AllocDiff is an
input-power-weighted difference between the two allocations, not energy transferred
between reconstructed modes: the masks act on amplitude, U_k = s_k X, so modal power
is s_k^2 P, and both rules preserve sum_k U_k = X while modal powers sum to P only
where the allocation is binary.  Because the Lorentzian mask has support everywhere,
it is a lower bound on the difference over the whole axis.

Each row also reports the transform, fs, duration, frame count, bin width (in hertz
and normalised), the neighbourhood width in hertz, and K_t as mean / median / min /
max with the total number of detections.  Table IV uses r = 1, 2, 3, 5.

DATA
----
The four signals are generated by ``synthetic_suite.py``; nothing has to be downloaded.
Table IV of the paper reports this same measurement on four third-party recordings that
are not included, so the values here are not the paper's values.

"""
